    const path = resolve(HAZARDS, f);
    const node = JSON.parse(await readFile(path, "utf-8")) as Record<string, unknown>;
    const id = node["@id"] as string;
    const slug = id.split(":")[1];
    const desc = HAZARD_DESCRIPTIONS[slug];
    if (!desc) { skipped++; continue; }
    node.description = desc;
    const meta = (node._meta as Record<string, unknown>) ?? {};
    meta.descriptionFilledAt = "2026-04-28";
